const paths: Record<string, any> = {};
for (const [m, p, tag, summary] of E) {
  paths[p] ??= {};
  const isPublic = p.startsWith('/public') || p.startsWith('/webhooks') || ['/auth/login', '/auth/mfa/verify', '/auth/refresh', '/auth/logout', '/auth/forgot-password', '/auth/reset-password'].includes(p);
  paths[p][m] = {
    tags: [tag], summary,
    ...(isPublic ? { security: [] } : {}),
    parameters: [...p.matchAll(/\{(\w+)\}/g)].map((x) => ({ name: x[1], in: 'path', required: true, schema: { type: 'string' } })),
    ...(m !== 'get' && { requestBody: { content: { 'application/json': { schema: { type: 'object' } } } } }),
    responses: { 200: { description: 'OK' }, 401: { description: 'Unauthenticated' }, 403: { description: 'Forbidden' }, 422: { description: 'Validation error' } },
  };
}

