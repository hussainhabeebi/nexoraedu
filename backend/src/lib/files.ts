/**
 * Private file storage on Cloudflare R2 (binding FILES). The bucket has no public access: every file is served
 * only by the API after an authorisation check (students photos, documents). Keys are random; no personal data
 * is ever part of a key.
 */
type R2Object = { body: ReadableStream; size: number; httpMetadata?: { contentType?: string } };
type R2Bucket = {
  put(key: string, value: ArrayBuffer | Uint8Array, opts?: { httpMetadata?: { contentType?: string } }): Promise<unknown>;
  get(key: string): Promise<R2Object | null>;
  head(key: string): Promise<unknown | null>;
  delete(key: string): Promise<void>;
};

let bucket: R2Bucket | undefined;
export function initFiles(b: R2Bucket) {
  bucket = b;
}
function files(): R2Bucket {
  if (!bucket) throw new Error('File storage not initialised (R2 binding FILES missing).');
  return bucket;
}

/** Stored names are 32 hex chars + an optional short extension (generated by the upload handler). */
export const isStoredName = (name: string) => /^[a-f0-9]{32}(\.[a-z0-9]{1,5})?$/.test(name);

export async function putFile(name: string, body: Uint8Array, contentType: string) {
  if (!isStoredName(name)) throw new Error('Invalid stored file name');
  await files().put(name, body, { httpMetadata: { contentType } });
}
export async function getFile(name: string) {
  if (!isStoredName(name)) return null;
  return files().get(name);
}
export async function deleteFile(name: string) {
  if (isStoredName(name)) await files().delete(name);
}
