/**
 * Writes migrations/0003_reference_data.sql: the production-safe reference data (roles, departments, branch,
 * master data, notification templates, approval workflows) produced by src/seed/reference.ts, as plain SQL.
 * Workers Builds applies it with the other migrations, so a new staging/production database is ready without
 * running any script. Contains NO users and NO passwords.
 *   npx tsx scripts/gen-reference-sql.ts
 */
import { mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { splitSql } from '../test/d1-sql';

for (const k of ['HTTPS_PROXY', 'HTTP_PROXY', 'https_proxy', 'http_proxy']) delete process.env[k];

async function main() {
  const { getPlatformProxy } = await import('wrangler');
  const dir = mkdtempSync(path.join(os.tmpdir(), 'nexora-ref-'));
  const p = await getPlatformProxy<{ DB: any }>({ configPath: path.resolve(__dirname, '../../wrangler.jsonc'), persist: { path: dir } });
  try {
    const db = p.env.DB;
    for (const f of readdirSync('migrations').filter((x) => /^000[12]_.*\.sql$/.test(x)).sort())
      await db.batch(splitSql(readFileSync(path.join('migrations', f), 'utf8')).map((s: string) => db.prepare(s)));
    const { initDb, prisma } = await import('../src/lib/prisma');
    initDb(db);
    const { seedReference } = await import('../src/seed/reference');
    await seedReference(prisma as any);
    const lit = (v: unknown) => (v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
    const out = ['-- Generated by scripts/gen-reference-sql.ts from src/seed/reference.ts. Reference data only: no users, no passwords.', ''];
    for (const t of ['roles', 'departments', 'branches', 'master_items', 'notification_templates', 'approval_workflows']) {
      const { results } = await db.prepare(`SELECT * FROM "${t}" ORDER BY rowid`).all();
      for (const r of results as Record<string, unknown>[]) {
        const cols = Object.keys(r);
        out.push(`INSERT INTO "${t}" (${cols.map((c) => `"${c}"`).join(', ')}) VALUES (${cols.map((c) => lit(r[c])).join(', ')}) ON CONFLICT DO NOTHING;`);
      }
    }
    writeFileSync('migrations/0003_reference_data.sql', out.join('\n') + '\n');
    console.log(`wrote migrations/0003_reference_data.sql (${out.length - 2} rows)`);
  } finally {
    await p.dispose();
    rmSync(dir, { recursive: true, force: true });
  }
}
main().catch((e) => {
  console.error(e);
  process.exitCode = 1;
});
