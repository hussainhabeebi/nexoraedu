/**
 * Regenerates the D1 (SQLite) migrations from the Prisma schema:
 *   0001_init.sql  – tables and indexes (`prisma migrate diff`), with SQLite-safe JSON defaults
 *   0002_rules.sql – database-enforced rules that Prisma cannot express (append-only tables, CHECK rules,
 *                    partial unique indexes, money precision, the in-batch assertion helper)
 * Run: node scripts/gen-d1-migrations.mjs   (only for a fresh schema; later changes are new numbered migrations)
 */
import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

let init = execSync('npx prisma migrate diff --from-empty --to-schema prisma/schema.prisma --script', { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] });
// SQLite needs JSON defaults as string literals.
init = init.replace(/DEFAULT ([\[{][^\n]*?[\]}]),?$/gm, (m, v) => `DEFAULT '${v}'${m.endsWith(',') ? ',' : ''}`);
writeFileSync('migrations/0001_init.sql', init);

const out = ['-- Generated by scripts/gen-d1-migrations.mjs. Database-enforced rules (the D1 equivalent of the PostgreSQL CHECKs/triggers).', ''];
const q = (s) => s.replace(/'/g, "''");

/** CHECK-style rule enforced on INSERT and UPDATE (SQLite cannot ADD CONSTRAINT to an existing table). */
function check(table, name, cond) {
  for (const op of ['INSERT', 'UPDATE']) {
    out.push(`CREATE TRIGGER "${table}_${name}_${op.toLowerCase()}" BEFORE ${op} ON "${table}" WHEN NOT (${cond.replace(/"(\w+)"/g, 'NEW."$1"')})`);
    out.push(`BEGIN SELECT RAISE(ABORT, 'CHECK constraint failed: ${q(table)}_${q(name)}'); END;`);
  }
}

// 1. Append-only tables (ledger, audit and history) — same list as PostgreSQL.
out.push('-- Append-only tables');
for (const t of ['audit_logs', 'ledger_entries', 'lead_activities', 'student_history', 'approval_actions', 'login_logs', 'integration_logs']) {
  for (const op of ['UPDATE', 'DELETE'])
    out.push(`CREATE TRIGGER "${t}_immutable_${op.toLowerCase()}" BEFORE ${op} ON "${t}" BEGIN SELECT RAISE(ABORT, 'Table ${t} is append-only; ${op} is not permitted'); END;`);
}

// 1b. Same rules the PostgreSQL runtime role had through GRANT/REVOKE (prisma/sql/app-role.sql):
//     enrollment history and fee adjustments are never deleted; notification logs only change delivery status.
for (const t of ['enrollments', 'fee_adjustments', 'notification_logs'])
  out.push(`CREATE TRIGGER "${t}_no_delete" BEFORE DELETE ON "${t}" BEGIN SELECT RAISE(ABORT, 'Rows in ${t} are never deleted (history)'); END;`);
{
  const cols = [];
  let inT = false;
  for (const line of init.split('\n')) {
    if (/^CREATE TABLE "notification_logs"/.test(line)) inT = true;
    else if (inT && /^\);/.test(line)) break;
    else if (inT) { const c = line.match(/^\s+"(\w+)"/); if (c) cols.push(c[1]); }
  }
  const frozen = cols.filter((c) => !['status', 'error', 'updatedAt', 'attempts'].includes(c));
  out.push(`CREATE TRIGGER "notification_logs_frozen_columns" BEFORE UPDATE ON "notification_logs" WHEN ${frozen.map((c) => `NEW."${c}" IS NOT OLD."${c}"`).join(' OR ')} BEGIN SELECT RAISE(ABORT, 'notification_logs: only delivery status may change'); END;`);
}

// 2. Money: every stored amount has at most 2 decimals and is never negative (no floating-point drift can be stored).
out.push('', '-- Money precision (Decimal columns are REAL in SQLite)');
let table = null;
for (const line of init.split('\n')) {
  const t = line.match(/^CREATE TABLE "(\w+)"/);
  if (t) table = t[1];
  const c = line.match(/^\s+"(\w+)" DECIMAL/);
  if (c && table) check(table, `${c[1]}_money`, `"${c[1]}" IS NULL OR ("${c[1]}" = round("${c[1]}", 2) AND "${c[1]}" >= 0)`);
}

// 3. Business CHECK rules ported from the PostgreSQL migrations.
out.push('', '-- Business rules');
check('fee_plans', 'dueAnchorDay', `"dueAnchorDay" IS NULL OR ("dueAnchorDay" BETWEEN 1 AND 31)`);
check('enrollments', 'status', `"status" IN ('ACTIVE','ON_HOLD','COMPLETED','TRANSFERRED','WITHDRAWN','TERMINATED','CANCELLED')`);
check('enrollments', 'source', `"source" IN ('ADMISSION','DIRECT','TRANSFER','COURSE_CHANGE','REACTIVATION','BACKFILL')`);
check('enrollments', 'end', `(("status" IN ('ACTIVE','ON_HOLD')) = ("endedAt" IS NULL)) AND ("endedAt" IS NULL OR "endedAt" >= "startDate")`);
check('fee_adjustments', 'kind', `"kind" IN ('WAIVER','RESCHEDULE','REBILL')`);
check('fee_adjustments', 'status', `"status" IN ('PENDING_APPROVAL','APPLIED','REJECTED')`);
check('fee_adjustments', 'amount', `"amount" > 0`);
check('fee_adjustments', 'schedule', `("kind" = 'RESCHEDULE') = ("schedule" IS NOT NULL)`);
check('fee_adjustments', 'applied', `("status" = 'APPLIED') = ("appliedAt" IS NOT NULL)`);
check('fee_adjustments', 'newplan', `("kind" = 'REBILL') = ("newPlan" IS NOT NULL)`);
check('fee_adjustments', 'created_plan', `("createdFeePlanId" IS NULL OR ("kind" = 'REBILL' AND "status" = 'APPLIED')) AND ("kind" <> 'REBILL' OR "status" <> 'APPLIED' OR "createdFeePlanId" IS NOT NULL)`);
check('installments', 'superseded', `"status" <> 'SUPERSEDED' OR ("amount" = 0 AND "paidAmount" = 0 AND "supersededAt" IS NOT NULL)`);
check('installments', 'paid_le_amount', `"paidAmount" <= "amount"`);

out.push('', '-- Partial unique indexes');
out.push(`CREATE UNIQUE INDEX "enrollments_one_current_per_student" ON "enrollments"("studentId") WHERE "status" IN ('ACTIVE', 'ON_HOLD');`);
out.push(`CREATE UNIQUE INDEX "fee_adjustments_one_pending_per_plan" ON "fee_adjustments"("feePlanId") WHERE "status" = 'PENDING_APPROVAL';`);
out.push(`CREATE UNIQUE INDEX "fee_adjustments_created_plan_key" ON "fee_adjustments"("createdFeePlanId") WHERE "createdFeePlanId" IS NOT NULL;`);

// 4. In-batch assertions (lib/db.ts): INSERT INTO "_assert" (ok, msg) VALUES ((<condition>), 'message')
//    aborts the whole D1 batch with `message` when the condition is not true. Nothing is ever stored.
out.push('', '-- Assertion helper for atomic batches');
out.push(`CREATE VIEW "_assert" AS SELECT 1 AS ok, '' AS msg;`);
out.push(`CREATE TRIGGER "_assert_insert" INSTEAD OF INSERT ON "_assert" WHEN NEW.ok IS NOT 1 BEGIN SELECT RAISE(ABORT, NEW.msg); END;`);
out.push(`CREATE TRIGGER "_assert_noop" INSTEAD OF INSERT ON "_assert" WHEN NEW.ok IS 1 BEGIN SELECT 1; END;`);
out.push('', '-- Optimistic locks for atomic batches (tx.lock in lib/db.ts; replaces SELECT … FOR UPDATE)');
out.push(`CREATE TABLE "_locks" ("key" TEXT NOT NULL PRIMARY KEY, "version" INTEGER NOT NULL);`);
out.push('', '-- Rate-limit counters shared by all Worker instances (lib/rate-store.ts)');
out.push(`CREATE TABLE "_rate_limits" ("key" TEXT NOT NULL PRIMARY KEY, "hits" INTEGER NOT NULL, "resetAt" INTEGER NOT NULL);`);
writeFileSync('migrations/0002_rules.sql', out.join('\n') + '\n');
console.log('wrote migrations/0001_init.sql and migrations/0002_rules.sql');
